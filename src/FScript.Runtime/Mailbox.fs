/// One worker drains each burst. An idle mailbox owns no running task.
type internal Inbox<'message, 'state> internal (capacity: int, initialState: 'state) =
    let gate = obj()
    let queue = Queue<'message>()
    let mutable state = initialState
    let mutable running = false
    let mutable closed = false
    let mutable pendingPosts = 0
    let mutable failure = None

    let checkFailure () =
        match failure with
        | Some error -> raise error
        | None -> ()

    let run (handle: 'state -> 'message -> 'state) =
        let take () =
            lock gate (fun () ->
                if queue.Count = 0 then
                    running <- false
                    Monitor.PulseAll gate
                    None
                else
                    let message = queue.Dequeue()
                    Monitor.PulseAll gate
                    Some message)
        try
            let mutable next = take ()
            while next.IsSome do
                state <- handle state next.Value
                next <- take ()
        with error ->
            lock gate (fun () ->
                failure <- Some error
                queue.Clear()
                running <- false
                Monitor.PulseAll gate)
            reraise ()

    let wait checkRuntime =
        Monitor.Wait(gate, 100) |> ignore
        checkRuntime ()

    member internal _.Post(message: 'message, startWorker: (('state -> 'message -> 'state) -> unit) -> unit, checkRuntime) =
        lock gate (fun () ->
            if closed then raise (ExtensionException("Cannot post to a finished mailbox."))
            pendingPosts <- pendingPosts + 1
            try
                while queue.Count = capacity && failure.IsNone do
                    wait checkRuntime
                checkFailure ()
                queue.Enqueue message
                if not running then
                    running <- true
                    try startWorker run
                    with _ ->
                        running <- false
                        queue.Clear()
                        reraise ()
            finally
                pendingPosts <- pendingPosts - 1
                Monitor.PulseAll gate)

    member internal _.Finish(checkRuntime) =
        lock gate (fun () ->
            closed <- true
            while (running || pendingPosts > 0) && failure.IsNone do
                wait checkRuntime
            checkFailure ()
            state)

[<Sealed>]
type MailboxInstance<'message, 'state> internal (queue: Inbox<'message, 'state>, handler: 'state -> 'message -> 'state) =
    member internal _.Queue: Inbox<'message, 'state> = queue
    member internal _.Handler: 'state -> 'message -> 'state = handler

/// Typed CLR entry points for code generated by FScript.
[<AbstractClass; Sealed>]
type CompiledMailbox private () =
    static member internal Capacity(capacity: int64) =
        if capacity <= 0L || capacity > int64 Int32.MaxValue then
            raise (ExtensionException("Mailbox.start capacity must be between 1 and 2147483647."))
        int capacity

    // The handler is carried separately from the queue to share exactly the same
    // admission and shutdown code with the interpreter adapter.
    static member Start<'message, 'state>(capacity: int64, handler: Func<'state, Func<'message, 'state>>, initialState: 'state) =
        let queue = Inbox<'message, 'state>(CompiledMailbox.Capacity capacity, initialState)
        MailboxInstance<'message, 'state>(queue, fun state message -> (handler.Invoke state).Invoke message)

    static member Post<'message, 'state>(message: 'message, inbox: MailboxInstance<'message, 'state>, schedule: Action<Action>) =
        inbox.Queue.Post(message, (fun run -> schedule.Invoke(Action(fun () -> run inbox.Handler))), ignore)

    static member Finish<'message, 'state>(inbox: MailboxInstance<'message, 'state>) =
        inbox.Queue.Finish ignore

    static member FScriptCompiledTypes () : IEnumerable<KeyValuePair<string, Type>> =
        [ KeyValuePair("Mailbox", typedefof<MailboxInstance<_, _>>) ]

    static member FScriptCompiledFunctions () : IEnumerable<KeyValuePair<string, MethodInfo>> =
        [ KeyValuePair("Mailbox.start", typeof<CompiledMailbox>.GetMethod("Start"))
          KeyValuePair("Mailbox.finish", typeof<CompiledMailbox>.GetMethod("Finish")) ]

    static member FScriptCompiledWorkerFunctions () : IEnumerable<KeyValuePair<string, MethodInfo>> =
        [ KeyValuePair("Mailbox.post", typeof<CompiledMailbox>.GetMethod("Post")) ]

type private InterpreterMailbox =
    { Queue: Inbox<ScriptValue, ScriptValue>
      Handler: ScriptValue }

module MailboxProvider =
    let private descriptor =
        { Name = "Mailbox"; HostManaged = true; Fields = Map.empty; TypeParameters = [0; 1] }

    let private types = { HostInterop.empty with Types = [descriptor] }

    let private message, state = TVar 0, TVar 1
    let private handle = TApplied(descriptor.Name, [message; state])
    let private operation name args result impl =
        { Name = "Mailbox." + name; Arity = List.length args
          Scheme = Forall([0; 1], List.foldBack (fun arg rest -> TFun(arg, rest)) args result)
          Impl = impl }

    let private inbox value =
        match (HostInterop.unwrap descriptor.Name value).Payload with
        | :? InterpreterMailbox as value -> value
        | _ -> raise (ExtensionException("Expected a mailbox handle."))

    let internal registerWithWorker (schedule: ExternalCallContext -> (ExternalCallContext -> unit) -> unit) : ExtensionRegistration =
        let functions =
              [ operation "start" [TInt; TFun(state, TFun(message, state)); state] handle (fun _ -> function
                  | [VInt capacity; handler; initial] ->
                      let inbox = { Queue = Inbox(CompiledMailbox.Capacity capacity, initial); Handler = handler }
                      HostInterop.create types descriptor.Name Map.empty inbox
                  | _ -> raise (ExtensionException("Mailbox.start capacity must be between 1 and 2147483647.")))
                operation "post" [message; handle] TUnit (fun context -> function
                  | [message; handle] ->
                      let mailbox = inbox handle
                      mailbox.Queue.Post(message, (fun run ->
                          schedule context (fun worker ->
                              run (fun state message -> worker.Apply (worker.Apply mailbox.Handler state) message))
                          ), context.CheckRuntime)
                      VUnit
                  | _ -> raise (ExtensionException("Mailbox.post expects a message and a mailbox.")))
                operation "finish" [handle] state (fun context -> function
                  | [handle] -> (inbox handle).Queue.Finish(context.CheckRuntime)
                  | _ -> raise (ExtensionException("Mailbox.finish expects a mailbox."))) ]
        { types with Functions = functions }

    let register () = registerWithWorker ExtensionBridge.spawnWorker
